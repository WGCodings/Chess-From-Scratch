// Embeds the Rust templates and the runtime crate's sources into
// src/embedded.generated.ts, so the generator works in the browser with no
// file system. Runs automatically before build, typecheck and test.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(pkg, "..", "..");
const runtime = join(repo, "crates", "cfs-runtime");

const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

const version = /\[workspace\.package\][^[]*?version\s*=\s*"([^"]+)"/s.exec(
  read(join(repo, "Cargo.toml")),
)?.[1];
if (!version) throw new Error("workspace version not found in Cargo.toml");

const sources = { LICENSE: read(join(runtime, "LICENSE")) };
for (const f of readdirSync(join(runtime, "src")).sort()) {
  if (f.endsWith(".rs")) sources[`src/${f}`] = read(join(runtime, "src", f));
}

const templates = {};
for (const f of readdirSync(join(pkg, "templates")).sort()) {
  if (f.endsWith(".rs")) templates[f.replace(/\.rs$/, "")] = read(join(pkg, "templates", f));
}

const out = `// Generated by scripts/embed.mjs. Do not edit.
/* eslint-disable */
export const RUNTIME_VERSION = ${JSON.stringify(version)};
export const RUNTIME_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};
export const TEMPLATES = ${JSON.stringify(templates, null, 2)} as const;
`;
writeFileSync(join(pkg, "src", "embedded.generated.ts"), out);
