// Embeds the Rust templates into src/embedded.generated.ts, so the
// generator works in the browser with no file system. Runs automatically
// before build, typecheck and test.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(p, "utf8").replace(/\r\n/g, "\n");

const templates = {};
for (const f of readdirSync(join(pkg, "templates")).sort()) {
  if (f.endsWith(".rs")) templates[f.replace(/\.rs$/, "")] = read(join(pkg, "templates", f));
}

const out = `// Generated by scripts/embed.mjs. Do not edit.
export const TEMPLATES = ${JSON.stringify(templates, null, 2)} as const;
`;
writeFileSync(join(pkg, "src", "embedded.generated.ts"), out);
