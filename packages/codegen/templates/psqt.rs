/// The piece-square score of the position, White minus Black.
pub fn psqt(board: &Board) -> S {
    let tables = [
        (Piece::Pawn, &PAWN_PSQT),
        (Piece::Knight, &KNIGHT_PSQT),
        (Piece::Bishop, &BISHOP_PSQT),
        (Piece::Rook, &ROOK_PSQT),
        (Piece::Queen, &QUEEN_PSQT),
        (Piece::King, &KING_PSQT),
    ];
    let mut score = S::default();
    for (piece, table) in tables {
        // A White piece on a1 (square 0) reads the bottom-left entry: index 56.
        for sq in board.colored_pieces(Color::White, piece) {
            score += table[sq as usize ^ 56];
        }
        // Black reads the table mirrored: its a8 is White's a1.
        for sq in board.colored_pieces(Color::Black, piece) {
            score -= table[sq as usize];
        }
    }
    score
}
